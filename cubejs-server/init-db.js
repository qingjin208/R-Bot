const { Client } = require('pg');

const NEON_URL = process.env.NEON_DIRECT_URL;
if (!NEON_URL) {
  console.error(
    '错误：未设置 NEON_DIRECT_URL 环境变量。\n' +
      '请设置你的 Neon Direct 连接串（用于初始化建表灌数据）。\n' +
      '在 cubejs-server 目录运行：\n' +
      '  NEON_DIRECT_URL="postgresql://user:pass@host:5432/neondb" node init-db.js'
  );
  process.exit(1);
}

const insertCustomer = 'INSERT INTO customers (name, city, region) VALUES ($1, $2, $3)';
const insertProduct = 'INSERT INTO products (name, category, price) VALUES ($1, $2, $3)';
const insertOrder =
  'INSERT INTO orders (order_date, customer_id, product_id, amount, quantity, region, status) ' +
  'VALUES ($1, $2, $3, $4, $5, $6, $7)';

